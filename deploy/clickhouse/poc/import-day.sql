-- C1 POC:FTP TRAFFIC CSV(PAN-OS WebUI 匯出,第一列欄位名稱)→ netops.pa_traffic_logs。
-- 由 import-day.sh 以 clickhouse-client 執行,CSV 從 stdin 送入(input())。依欄位「名稱」對應(同 backend palog.js 的 COLUMNS),
-- 不在下面結構裡的欄位(FTP CSV 有 130 欄)略過:input_format_skip_unknown_fields=1。
-- 時間:CSV 是 PA-560 本地時間(Asia/Taipei)「2026/11/09 23:58:30」。IP:IPv4 轉成 ::ffff:a.b.c.d,空值 → ::。
INSERT INTO netops.pa_traffic_logs
SELECT
    parseDateTimeOrZero(`Receive Time`, '%Y/%m/%d %H:%i:%S', 'Asia/Taipei')            AS event_time,
    toDateTime64(event_time, 3, 'Asia/Taipei')                                          AS received_at,
    toUInt64OrZero(`Sequence Number`)                                                   AS seqno,
    toUInt32OrZero(`Session ID`)                                                        AS session_id,
    `Threat/Content Type`                                                               AS subtype,
    toIPv6OrDefault(`Source address`)                                                   AS src,
    toIPv6OrDefault(`Destination address`)                                              AS dst,
    toIPv6OrDefault(`NAT Source IP`)                                                    AS nat_src,
    toIPv6OrDefault(`NAT Destination IP`)                                               AS nat_dst,
    toUInt16OrZero(`Source Port`)                                                       AS sport,
    toUInt16OrZero(`Destination Port`)                                                  AS dport,
    toUInt16OrZero(`NAT Destination Port`)                                              AS nat_dport,
    `IP Protocol`                                                                       AS proto,
    `Rule`                                                                              AS rule,
    `Source User`                                                                       AS src_user,
    `Application`                                                                       AS app,
    `Source Zone`                                                                       AS from_zone,
    `Destination Zone`                                                                  AS to_zone,
    `Inbound Interface`                                                                 AS in_if,
    `Outbound Interface`                                                                AS out_if,
    `Action`                                                                            AS action,
    toUInt64OrZero(`Bytes`)                                                             AS bytes,
    toUInt64OrZero(`Bytes Sent`)                                                        AS bytes_sent,
    toUInt64OrZero(`Bytes Received`)                                                    AS bytes_recv,
    toUInt64OrZero(`Packets`)                                                           AS packets,
    parseDateTimeOrZero(`Start Time`, '%Y/%m/%d %H:%i:%S', 'Asia/Taipei')              AS session_start,
    toUInt32OrZero(`Elapsed Time (sec)`)                                                AS elapsed,
    `Category`                                                                          AS category,
    `Source Country`                                                                    AS src_country,
    `Destination Country`                                                               AS dst_country,
    `Session End Reason`                                                                AS end_reason,
    toUInt8OrZero(`Risk of app`)                                                        AS app_risk,
    `Category of app`                                                                   AS app_category,
    `Subcategory of app`                                                                AS app_subcat,
    `Technology of app`                                                                 AS app_tech,
    `Source Hostname`                                                                   AS src_host,
    `Destination Hostname`                                                              AS dst_host,
    'ftp'                                                                               AS source
FROM input('`Receive Time` String, `Sequence Number` String, `Session ID` String, `Threat/Content Type` String,
            `Source address` String, `Destination address` String, `NAT Source IP` String, `NAT Destination IP` String,
            `Source Port` String, `Destination Port` String, `NAT Destination Port` String, `IP Protocol` String,
            `Rule` String, `Source User` String, `Application` String, `Source Zone` String, `Destination Zone` String,
            `Inbound Interface` String, `Outbound Interface` String, `Action` String, `Bytes` String, `Bytes Sent` String,
            `Bytes Received` String, `Packets` String, `Start Time` String, `Elapsed Time (sec)` String, `Category` String,
            `Source Country` String, `Destination Country` String, `Session End Reason` String, `Risk of app` String,
            `Category of app` String, `Subcategory of app` String, `Technology of app` String,
            `Source Hostname` String, `Destination Hostname` String')
SETTINGS input_format_with_names_use_header = 1, input_format_skip_unknown_fields = 1,
         input_format_csv_empty_as_default = 1, input_format_allow_errors_num = 0
FORMAT CSVWithNames
